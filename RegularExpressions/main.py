# 1. Напишите регулярное выражение, которое находит слово голладец в «Дзене Пайтона».
import re

text = """Красивое лучше, чем уродливое.
Явное лучше, чем неявное.
...
Голладец — это вымышленный персонаж.
Но в Дзене Пайтона такого слова нет."""

matches = re.findall(r'\bголладец\b', text, re.IGNORECASE)
print(matches)  # ['голладец']

# 2. Создайте регулярное выражение, которое находит все цифры в строке Москва: 777, 999, 797. Тула: 071, 950, 112..
import re

text = "Москва: 777, 999, 797. Тула: 071, 950, 112."

# Найти все последовательности цифр
numbers = re.findall(r'\d+', text)
print(numbers)  # ['777', '999', '797', '071', '950', '112']

# Найти каждую отдельную цифру
digits = re.findall(r'\d', text)
print(digits)  # ['7', '7', '7', '9', '9', '9', '7', '9', '7', '0', '7', '1', '9', '5', '0', '1', '1', '2']

# 3. Создайте регулярное выражение для нахождения любого слова, которое начинается с произвольного символа, предшествующего буквам ло.
# Затем используйте модуль re из Python, чтобы найти сочетания ало и зло в предложении Привидение прошуршало и и исчезло в углу.
import re

# Исходное предложение
text = "Привидение прошуршало и исчезло в углу."

# Регулярное выражение для слов, содержащих "ало" или "зло"
# \b — граница слова
# \w* — любое количество букв/цифр/знаков подчёркивания
# [аз] — символ а или з
# ло — искомая последовательность
pattern = r'\b\w*[аз]ло\w*\b'

# Поиск всех совпадений
matches = re.findall(pattern, text)

print(matches)  # ['прошуршало', 'исчезло']